import { Difficulty, QuestionStatus } from '@prisma/client';

export interface SeedOption {
  id: string;
  text: string;
  sortOrder: number;
  isCorrect: boolean;
}

export interface SeedQuestion {
  id: string;
  text: string;
  explanation: string;
  difficulty: Difficulty;
  status: QuestionStatus;
  categoryId: string;
  options: SeedOption[];
}

const CAT_GEN = '00000000-0000-4000-b000-000000000001';
const CAT_HIST = '00000000-0000-4000-b000-000000000002';
const CAT_GEO = '00000000-0000-4000-b000-000000000003';
const CAT_TECH = '00000000-0000-4000-b000-000000000004';

function qId(num: number): string {
  return `00000000-0000-4000-d000-${String(num).padStart(12, '0')}`;
}

function optId(qNum: number, sortOrder: number): string {
  return `00000000-0000-4000-e${String(qNum).padStart(3, '0')}-00000000000${sortOrder}`;
}

function buildQuestion(
  num: number,
  categoryId: string,
  difficulty: Difficulty,
  status: QuestionStatus,
  text: string,
  explanation: string,
  opts: [string, string, string, string],
  correctIndex: number,
): SeedQuestion {
  return {
    id: qId(num),
    categoryId,
    difficulty,
    status,
    text,
    explanation,
    options: opts.map((optText, idx) => ({
      id: optId(num, idx + 1),
      text: optText,
      sortOrder: idx + 1,
      isCorrect: idx === correctIndex,
    })),
  };
}

